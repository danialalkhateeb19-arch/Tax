/** ملخص سنة واحدة: { salary, tax, months } — الضريبة محسوبة بالسلّم التصاعدي. */
/**
 * ملخص سنة واحدة: { year, salary, tax, months, paid, settled }
 *
 * الضريبة بالروبل الصحيح — مصلحة الضرائب لا تتعامل بالكوبيك.
 *
 * السنة المسدّدة تعتمد **المبلغ المدفوع فعلاً** لا نتيجة المعادلة، لأن
 * المدفوع هو التقدير الرسمي المعروف، بينما المعادلة إعادة بناء تقريبية
 * (الاستقطاع الشهري التراكمي يُقرَّب كل شهر، فيفرق عن التقريب السنوي
 * بروبل أو اثنين). المعادلة تعمل على السنوات المفتوحة فقط.
 */
export function yearSummary(year) {
  const rows = TAX_HISTORY[year] || [];
  const baseSalary = Math.round(rows.reduce((s, r) => s + r[1], 0) * 100) / 100;
  // [تعديل الإيداع] كل إيداع مصنّف «ضريبة» = ضريبة شهر لم يُسجَّل بعد،
  // فيُستخرج منه الراتب المقابل ويُضاف للسنة. الشهور المسجّلة أعلاه لا تتكرّر
  // لأن الإيداعات تُحسب من LIVE_TRACKING_FROM فقط.
  const extraTax = Math.max(0, Number(liveTaxDepositsFor(Number(year))) || 0);
  const totalTax = computeTax(year, baseSalary) + extraTax;
  const salary = extraTax > 0 ? salaryForTax(year, totalTax) : baseSalary;
  const computed = Math.round(totalTax);
  const paid = Number((OPENING.paidSoFar || {})[year]) || 0;
  const settled = paid > 0 && Math.abs(paid - computed) <= 2;
  return {
    year: Number(year),
    salary,
    tax: settled ? paid : computed,
    computed,
    paid,
    settled,
    months: rows.filter((r) => r[1] > 0).length,
  };
}

/** كل السنوات مرتّبة تنازلياً (الأحدث أولاً) — للعرض في البطاقة. */
export function allYearSummaries() {
  return Object.keys(TAX_HISTORY)
    .map(yearSummary)
    .sort((a, b) => b.year - a.year);
}

/** إجمالي الالتزام الضريبي عبر كل السنوات. */
export function totalObligation() {
  return allYearSummaries().reduce((s, y) => s + y.tax, 0);
}

/** إجمالي المدفوع حسب الأرصدة الافتتاحية. */
export function totalPaid() {
  return Object.values(OPENING.paidSoFar)
    .reduce((s, v) => s + (Number(v) || 0), 0);
}

/** المتبقّي المستحق = الالتزام − المدفوع. */
export function remainingDue() {
  return totalObligation() - totalPaid();
}
